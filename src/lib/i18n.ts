export function translate(lang: Lang, key: string): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export function t(lang: Lang, key: string): string {
  return translate(lang, key);
}

// Helper to get a translated value from a JSONB field
export function getTranslatedValue(value: Record<string, string> | null | undefined, lang: Lang): string {
  if (!value) return '';
  return value[lang] || value['ru'] || value['en'] || Object.values(value)[0] || '';
}

// Format price with currency conversion
export function formatPrice(price: number, fromCurrency: CurrencyCode, toCurrency: CurrencyCode, lang: Lang): string {
  const rate = EXCHANGE_RATES[fromCurrency] / EXCHANGE_RATES[toCurrency];
  const converted = price * rate;
  const formatted = new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'ru-RU').format(Math.round(converted));
  return `${formatted} ${CURRENCIES[toCurrency].symbol}`;
}
